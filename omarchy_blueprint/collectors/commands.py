"""Commands in ~/.local/bin and ~/bin.

A link into a repo or plugin is recreated by the bootstrap task, after the
repos exist. A script you wrote is carried as a file. A binary some installer
dropped there needs that installer, or a mise tool instead.
"""

from __future__ import annotations

import os
import re
from pathlib import Path

from ..env import Env, glob, is_junk, is_text, item, mode_of, read_text, split_lines

INSTALLED_HEADER = re.compile(r"install(s|ed)? (it|this|as)|generated by|do not edit", re.I)


def header_of(lines: list[str]) -> str:
    """The comment lines after the shebang (up to five): what the script is, who installs it."""
    out = []
    for line in lines[1:8]:
        if not line.startswith("#"):
            break
        out.append(re.sub(r"^# ?", "", line))
    return "\n".join(out[:5])


def wrapped_path(env: Env, text: str) -> str:
    """The first path under a hidden folder or ~/.local/share the script runs from, if any."""
    h = str(env.home)
    pat = re.compile("(" + re.escape(h) + r"|\$HOME|~)/\.(local/share|[a-z][^/]*)/[^\"' )]*")
    for line in split_lines(text):
        for m in pat.finditer(line):
            p = m.group(0)
            if re.search(r"/\.(config|ssh|cache)/|/\.local/share/mise/", p):
                continue
            return re.sub(r"^~", h, re.sub(r"^\$HOME", h, p))
    return ""


def collect(env: Env) -> list[dict]:
    h = str(env.home)
    items = []
    for d in (h + "/.local/bin", h + "/bin"):
        if not os.path.isdir(d):
            continue
        for f in glob(d + "/*"):
            if not (os.path.exists(f) or os.path.islink(f)) or is_junk(env, f):
                continue
            name = env.home_rel(f)
            if os.path.islink(f):
                target = os.path.realpath(f)
                facts = {"path": name, "target": env.home_rel(target)}
                if not os.path.exists(target):
                    items.append(item("link", name, "skip", f"A broken link to {env.home_rel(target)}.", facts))
                elif target.startswith(h + "/.local/share/"):
                    items.append(item("link", name, "review", f"Points into {env.home_rel(target)}, which some installer "
                                      "manages. Find that installer, or install the tool with mise.", facts))
                elif target.startswith(h + "/.config/omarchy/plugins/") or \
                        env.run("git", "-C", os.path.dirname(target), "rev-parse", "--git-dir").ok:
                    items.append(item("link", name, "carry", f"Links into {env.home_rel(os.path.dirname(target))}. "
                                      "Recreate it in the bootstrap task, after repos are cloned.", facts))
                elif target.startswith(h + "/."):
                    items.append(item("link", name, "review", f"Links into {env.home_rel(os.path.dirname(target))}, "
                                      "which an installer manages. Run that installer on the new machine instead.", facts))
                else:
                    items.append(item("link", name, "review", f"Links to {target}, outside your home.", facts))
            elif is_text(f) and Path(f).read_bytes()[:2] == b"#!":
                text = read_text(f)
                header = header_of(split_lines(text))
                wraps = wrapped_path(env, text)
                facts = {"path": name, "text": True, "mode": mode_of(f), "header": header}
                if wraps:
                    facts["wraps"] = wraps
                if env.corpus.writes_command(os.path.basename(f)):
                    items.append(item("command", name, "skip", "Omarchy or one of its installers writes it.", facts))
                elif wraps:
                    under = "/".join(env.home_rel(wraps).split("/")[:4])
                    items.append(item("command", name, "review", f"A wrapper around something installed under {under}. "
                                      "Reinstall that instead of carrying the wrapper.", facts))
                elif INSTALLED_HEADER.search(header):
                    items.append(item("command", name, "review", "Its header says another tool installs or generates "
                                      f"it: {header.split(chr(10))[0]}", facts))
                else:
                    items.append(item("command", name, "carry", "A script you wrote.", facts))
            else:
                kind = env.run("file", "-b", f).out.strip().split(",")[0]
                items.append(item("command", name, "review", f"A binary, so some installer put it here ({kind}). "
                                  "Install it with mise or its installer instead.", {"path": name, "size": os.lstat(f).st_size}))
    return items
